/** Python emitter: keyword-only dataclass models plus a sync and an async resource class per tag. */
import { sdkVersion, type GeneratedFile } from '../index.ts';
import { assertSupportedBody } from '../ir.ts';
import type { EnumType, Group, NamedType, ObjectType, Operation, Param, Property, Spec, TypeRef } from '../ir.ts';
import { pythonIdent, screamingSnake, snake } from '../naming.ts';
import { Writer } from '../writer.ts';

/** Body encodings this emitter can render. */
const SUPPORTED_BODIES = ['json', 'multipart', 'binary', 'form', 'text'] as const;

const HEADER = '# Code generated by @uarp/codegen from spec/openapi.json. DO NOT EDIT.';

/** PEP 8 indentation. */
const PY_INDENT = '    ';

/**
 * Names the models module imports. A spec type with one of these names would
 * shadow the import and break every annotation that uses it, so it stops the
 * build instead.
 */
const MODEL_IMPORTS = [
  'Any', 'Dict', 'List', 'Optional', 'TypeAlias',
  'FileInput', 'JsonObject', 'JsonValue', 'Model', 'UarpEnum',
];

/** The attribute an open model keeps undeclared members in (`_models.ADDITIONAL`). */
const ADDITIONAL = 'additional_properties';

/** The spec's named types, for the emitters that need a body's or a page's fields. */
let types = new Map<string, NamedType>();

export function emitPython(spec: Spec): GeneratedFile[] {
  for (const group of spec.groups) {
    for (const op of group.operations) assertSupportedBody(op, [...SUPPORTED_BODIES]);
  }
  types = new Map(spec.types.map((type) => [type.name, type]));
  for (const type of spec.types) {
    if (MODEL_IMPORTS.includes(type.name)) {
      throw new Error(`a schema named ${type.name} would shadow an import of the Python models module`);
    }
  }

  const root = 'src/uarp_sdk/generated';
  const files: GeneratedFile[] = [];
  const add = (path: string, content: string) => files.push({ path, content: pep8Blank(content) });
  add(`${root}/__init__.py`, `${HEADER}\n"""Code generated from the API document. Import from \`uarp_sdk\` instead."""\n`);
  add(`${root}/meta.py`, emitMeta(spec));
  add(`${root}/models.py`, emitModels(spec));
  add(`${root}/resources/__init__.py`, emitResourceIndex(spec));
  for (const group of spec.groups) {
    add(`${root}/resources/${moduleName(group)}.py`, emitGroup(group));
  }
  return files;
}

/**
 * PEP 8's blank lines, whatever the emitter wrote: two before a top-level
 * statement that follows a block, one inside a class, none doubled.
 */
function pep8Blank(text: string): string {
  const lines = text.split('\n');
  const out: string[] = [];
  for (let index = 0; index < lines.length; index++) {
    const line = lines[index]!;
    if (line.trim() !== '') {
      out.push(line);
      continue;
    }
    let end = index;
    while (end < lines.length && lines[end]!.trim() === '') end++;
    const next = lines[end];
    if (next === undefined) break;
    const previous = out[out.length - 1] ?? '';
    const topLevel = !/^\s/.test(next);
    const afterBlock = /^\s/.test(previous) || /^(class|def|async def|@)/.test(next);
    const blanks = topLevel && afterBlock && !next.startsWith('#') ? 2 : 1;
    for (let n = 0; n < blanks; n++) out.push('');
    index = end - 1;
  }
  return out.join('\n').replace(/\n*$/, '\n');
}

function moduleName(group: Group): string {
  return pythonIdent(snake(group.name));
}

function emitMeta(spec: Spec): string {
  const w = new Writer(PY_INDENT);
  w.line(HEADER);
  w.line('"""Versions and constants baked in at generation time."""');
  w.line();
  w.line('#: Version of the OpenAPI document this SDK was generated from.');
  w.line(`SPEC_VERSION = ${str(spec.version)}`);
  w.line();
  w.line('#: Version of this SDK.');
  w.line(`SDK_VERSION = ${str(sdkVersion())}`);
  w.line();
  w.line('#: Production base URL.');
  w.line(`DEFAULT_BASE_URL = ${str(spec.servers[0]?.url ?? 'https://api.snaga.ai')}`);
  w.line();
  w.line('#: Every scope named by the UARP security scheme.');
  w.line('SCOPES = (');
  w.indent(() => {
    for (const scope of spec.scopes) w.line(`${str(scope)},`);
  });
  w.line(')');
  return w.toString();
}

// ------------------------------------------------------------------- models

function emitModels(spec: Spec): string {
  const w = new Writer(PY_INDENT);
  w.line(HEADER);
  docstring(w, `Data models for ${spec.title} (spec version ${spec.version}).`);
  w.line();
  w.line('from __future__ import annotations');
  w.line();
  //  Underscored: a property named `field` would otherwise rebind the
  //  function for the rest of its class body.
  w.line('from dataclasses import dataclass as _dataclass');
  w.line('from dataclasses import field as _field');
  w.line('from typing import Any, Dict, List, Optional, TypeAlias');
  w.line();
  w.line('from .._models import FileInput, JsonObject, JsonValue, Model, UarpEnum');

  //  Enums first and aliases last: an enum depends on nothing, and an alias is
  //  evaluated when the module loads, so everything it names must exist by
  //  then. Classes refer to each other through postponed annotations.
  for (const type of spec.types) {
    if (type.kind !== 'enum') continue;
    w.line();
    w.line();
    emitEnum(w, type);
  }
  for (const type of spec.types) {
    if (type.kind !== 'object') continue;
    w.line();
    w.line();
    emitClass(w, type);
  }
  const aliases = spec.types.filter((type) => type.kind === 'alias');
  if (aliases.length > 0) {
    w.line();
    w.line();
    for (const type of aliases) {
      if (type.kind !== 'alias') continue;
      if (type.description) for (const line of commentLines(type.description)) w.line(`#: ${line}`);
      w.line(`${type.name}: TypeAlias = ${pyType(type.target)}`);
    }
  }
  w.line();
  w.line();
  w.line('__all__ = [');
  w.indent(() => {
    for (const type of [...spec.types].sort((a, b) => a.name.localeCompare(b.name))) w.line(`${str(type.name)},`);
  });
  w.line(']');
  return w.toString();
}

function emitEnum(w: Writer, type: EnumType): void {
  w.block(`class ${type.name}(UarpEnum):`, () => {
    docstring(w, type.description ?? `\`${type.name}\` enumeration.`);
    w.line();
    for (const member of enumMembers(type)) w.line(`${member.name} = ${str(member.wire)}`);
  }, '');
}

interface Member {
  name: string;
  wire: string;
}

function enumMembers(type: EnumType): Member[] {
  const used = new Set<string>();
  return type.values.map((value) => {
    let name = screamingSnake(value) || 'VALUE';
    if (/^[0-9]/.test(name)) name = `V_${name}`;
    if (used.has(name)) {
      let n = 2;
      while (used.has(`${name}_${n}`)) n++;
      name = `${name}_${n}`;
    }
    used.add(name);
    return { name, wire: value };
  });
}

function emitClass(w: Writer, type: ObjectType): void {
  w.line('@_dataclass(kw_only=True)');
  w.block(`class ${type.name}(Model):`, () => {
    docstring(w, type.description ?? `\`${type.name}\` model.`);
    const fields = modelFields(type);
    if (fields.length === 0 && !type.additional) return;
    for (const { prop, attribute } of fields) {
      w.line();
      const optional = !prop.required || prop.nullable;
      const inner = pyType(prop.type);
      const annotation = optional ? nullable(inner) : inner;
      const metadata = attribute !== prop.wire ? `metadata={${str('wire')}: ${str(prop.wire)}}` : undefined;
      if (prop.required) {
        //  Required: no default, so building a body without it is a TypeError
        //  rather than a request the server refuses.
        w.line(metadata ? `${attribute}: ${annotation} = _field(${metadata})` : `${attribute}: ${annotation}`);
      } else {
        w.line(metadata ? `${attribute}: ${annotation} = _field(default=None, ${metadata})` : `${attribute}: ${annotation} = None`);
      }
      const docs: string[] = [];
      if (prop.description) docs.push(prop.description);
      if (prop.constValue !== undefined) docs.push(`Always \`${prop.constValue}\`.`);
      if (prop.defaultValue !== undefined) docs.push(`Server default: \`${JSON.stringify(prop.defaultValue)}\`.`);
      if (prop.deprecated) docs.push('Deprecated.');
      docstring(w, docs.join('\n\n') || undefined);
    }
    if (type.additional) {
      w.line();
      w.line(
        `${ADDITIONAL}: Dict[str, Any] = _field(default_factory=dict, metadata={${str('additional')}: True})`,
      );
      docstring(w, 'Members the server sent that the document does not name, as sent.');
    }
  }, '');
}

/**
 * Each property with the attribute it becomes.
 *
 * Two wire names can fold into one snake_case attribute (`unread_count` and
 * `unreadCount` both do; the platform serves both in one object), so the later
 * one is suffixed. `additional_properties` is taken first on an open model.
 */
function modelFields(type: ObjectType): { prop: Property; attribute: string }[] {
  const used = new Set<string>(type.additional ? [ADDITIONAL] : []);
  return type.properties.map((prop) => {
    let attribute = pythonIdent(snake(prop.wire) || 'value');
    while (used.has(attribute)) attribute += '_';
    used.add(attribute);
    return { prop, attribute };
  });
}

/** The attribute a wire property of a named object type becomes, if it is one. */
function attributeOf(ref: TypeRef | undefined, wire: string): string | undefined {
  const type = ref?.kind === 'named' ? resolve(ref.name) : undefined;
  if (type?.kind !== 'object') return undefined;
  return modelFields(type).find((field) => field.prop.wire === wire)?.attribute;
}

function resolve(name: string): NamedType | undefined {
  let type = types.get(name);
  while (type?.kind === 'alias' && type.target.kind === 'named') type = types.get(type.target.name);
  return type;
}

/**
 * The annotation for a type. `typing` generics rather than `list[...]`: a
 * resource method named `list` would shadow the builtin inside its class.
 * Aliases are written out, so an annotation never depends on the order the
 * module defines things in.
 */
export function pyType(ref: TypeRef, qualifier = ''): string {
  switch (ref.kind) {
    case 'named': {
      const type = types.get(ref.name);
      if (type?.kind === 'alias') return pyType(type.target, qualifier);
      return `${qualifier}${ref.name}`;
    }
    case 'array':
      return `List[${pyType(ref.items, qualifier)}]`;
    case 'map':
      return `Dict[str, ${pyType(ref.values, qualifier)}]`;
    case 'union':
      //  No discriminator to choose a variant by; raw JSON keeps all of them,
      //  as the Rust and Kotlin SDKs do.
      return 'JsonValue';
    case 'prim':
      switch (ref.prim) {
        case 'string':
        case 'datetime':
        case 'date':
        case 'uuid':
        case 'uri':
        case 'email':
          return 'str';
        case 'integer':
          return 'int';
        case 'number':
          return 'float';
        case 'boolean':
          return 'bool';
        case 'binary':
          return 'FileInput';
        case 'jsonObject':
          return 'JsonObject';
        default:
          return 'JsonValue';
      }
  }
}

function nullable(annotation: string): string {
  return annotation === 'JsonValue' ? annotation : `Optional[${annotation}]`;
}

// ---------------------------------------------------------------- resources

function emitResourceIndex(spec: Spec): string {
  const w = new Writer(PY_INDENT);
  w.line(HEADER);
  w.line('"""Every resource group, as attributes of the client."""');
  w.line();
  w.line('from __future__ import annotations');
  w.line();
  w.line('import functools');
  w.line('from typing import TYPE_CHECKING, cast');
  w.line();
  for (const group of spec.groups) {
    w.line(`from .${moduleName(group)} import ${group.name}Resource, Async${group.name}Resource`);
  }
  w.line();
  w.block('if TYPE_CHECKING:', () => {
    w.line('from ..._transport import AsyncTransport, SyncTransport');
  }, '');
  for (const flavour of ['sync', 'async'] as const) {
    const prefix = flavour === 'async' ? 'Async' : '';
    const transport = flavour === 'async' ? 'AsyncTransport' : 'SyncTransport';
    w.line();
    w.block(`class ${flavour === 'async' ? 'AsyncResources' : 'SyncResources'}:`, () => {
      docstring(w, `The resource groups, as attributes of ${flavour === 'async' ? '`AsyncClient`' : '`Client`'}.`);
      for (const group of spec.groups) {
        w.line();
        w.line('@functools.cached_property');
        w.block(`def ${accessorName(group)}(self) -> ${prefix}${group.name}Resource:`, () => {
          docstring(w, group.description ?? `Operations tagged \`${group.tag}\`.`);
          w.line(`return ${prefix}${group.name}Resource(cast(${str(transport)}, self))`);
        }, '');
      }
    }, '');
  }
  w.line();
  w.line('__all__ = [');
  w.indent(() => {
    w.line(`${str('AsyncResources')},`);
    w.line(`${str('SyncResources')},`);
    for (const group of spec.groups) {
      w.line(`${str(`${group.name}Resource`)},`);
      w.line(`${str(`Async${group.name}Resource`)},`);
    }
  });
  w.line(']');
  return w.toString();
}

function accessorName(group: Group): string {
  return pythonIdent(snake(group.accessor));
}

function emitGroup(group: Group): string {
  const w = new Writer(PY_INDENT);
  w.line(HEADER);
  docstring(w, group.description ?? `Operations tagged \`${group.tag}\`.`);
  w.line();
  w.line('from __future__ import annotations');
  w.line();
  w.line('from typing import TYPE_CHECKING, Any, AsyncIterator, Dict, Iterator, List, Optional, Union');
  w.line('from typing import cast as _cast');
  w.line();
  w.line('from ..._files import FilePart');
  w.line('from ..._models import FileInput, JsonObject, JsonValue');
  w.line('from ..._pagination import CursorGuard as _CursorGuard');
  w.line('from ..._sse import AsyncEventStream, EventStream');
  w.line('from ..._transport import BINARY as _BINARY');
  w.line('from ..._transport import TEXT as _TEXT');
  w.line('from ..._transport import VOID as _VOID');
  w.line('from ..._transport import Body as _Body');
  w.line('from ..._transport import RequestOptions');
  w.line('from ..._transport import Response as _Response');
  w.line('from ..._util import path_segment as _segment');
  w.line('from .. import models as _m');
  w.line();
  w.block('if TYPE_CHECKING:', () => {
    w.line('from ..._transport import AsyncTransport, SyncTransport');
  }, '');
  w.line('__all__ = [');
  w.indent(() => {
    w.line(`${str(`${group.name}Resource`)},`);
    w.line(`${str(`Async${group.name}Resource`)},`);
  });
  w.line(']');

  for (const flavour of ['sync', 'async'] as const) {
    const name = flavour === 'async' ? `Async${group.name}Resource` : `${group.name}Resource`;
    w.line();
    w.line();
    w.block(`class ${name}:`, () => {
      docstring(w, group.description ?? `Operations tagged \`${group.tag}\`.`);
      w.line();
      w.block(`def __init__(self, client: ${flavour === 'async' ? 'AsyncTransport' : 'SyncTransport'}) -> None:`, () => {
        w.line('self._client = client');
      }, '');
      for (const op of group.operations) {
        w.line();
        emitOperation(w, op, flavour);
        if (canPaginate(op)) {
          w.line();
          emitPaginated(w, op, group, flavour);
        }
      }
    }, '');
  }
  return w.toString();
}

interface Arg {
  /** The Python parameter name. */
  name: string;
  annotation: string;
  /** `param` for a query or header parameter, which is keyword-only. */
  role: 'path' | 'body' | 'param';
  required: boolean;
  /** The IR parameter, for query and header parameters. */
  param?: Param;
}

/**
 * The method's parameters. Path parameters and the body are positional, in
 * that order; query and header parameters are keyword-only, so a call reads
 * `client.agents.list(limit=2)` and adding one later breaks nobody.
 */
function operationArgs(op: Operation): Arg[] {
  const used = new Set<string>(['self', 'request_options']);
  const unique = (wire: string): string => {
    let name = pythonIdent(snake(wire) || 'value');
    while (used.has(name)) name += '_';
    used.add(name);
    return name;
  };
  const args: Arg[] = [];
  for (const param of op.pathParams) {
    args.push({ name: unique(param.wire), annotation: pyType(param.type, '_m.'), role: 'path', required: true, param });
  }
  if (op.body) {
    used.add('body');
    args.push({ name: 'body', annotation: bodyAnnotation(op), role: 'body', required: op.body.required });
  }
  for (const param of [...op.queryParams, ...op.headerParams]) {
    args.push({ name: unique(param.wire), annotation: pyType(param.type, '_m.'), role: 'param', required: param.required, param });
  }
  return args;
}

function bodyAnnotation(op: Operation): string {
  const body = op.body!;
  if (body.encoding === 'binary') return 'Union[bytes, FilePart]';
  if (body.encoding === 'text') return 'str';
  const annotation = pyType(body.type, '_m.');
  //  A model, or the same object as a plain dict, which goes on the wire as
  //  it is — the way to send an explicit `null` for an optional property.
  const type = body.type.kind === 'named' ? resolve(body.type.name) : undefined;
  return type?.kind === 'object' ? `Union[${annotation}, Dict[str, Any]]` : annotation;
}

function signature(args: Arg[]): string {
  const parts = ['self'];
  for (const arg of args.filter((a) => a.role !== 'param')) {
    parts.push(arg.required ? `${arg.name}: ${arg.annotation}` : `${arg.name}: Optional[${arg.annotation}] = None`);
  }
  parts.push('*');
  for (const arg of args.filter((a) => a.role === 'param')) {
    parts.push(arg.required ? `${arg.name}: ${arg.annotation}` : `${arg.name}: ${nullable(arg.annotation)} = None`);
  }
  parts.push('request_options: Optional[RequestOptions] = None');
  return parts.join(', ');
}

function emitOperation(w: Writer, op: Operation, flavour: 'sync' | 'async'): void {
  const args = operationArgs(op);
  const name = methodName(op);
  const sig = signature(args);

  if (op.sse) {
    const returns = flavour === 'async' ? 'AsyncEventStream' : 'EventStream';
    w.block(`def ${name}(${sig}) -> ${returns}:`, () => {
      docstring(w, operationDoc(op, flavour));
      emitStreamCall(w, op, args);
    }, '');
    return;
  }

  const def = flavour === 'async' ? 'async def' : 'def';
  w.block(`${def} ${name}(${sig}) -> ${returnAnnotation(op)}:`, () => {
    docstring(w, operationDoc(op, flavour));
    emitCall(w, op, args, flavour);
  }, '');
}

function emitCall(w: Writer, op: Operation, args: Arg[], flavour: 'sync' | 'async'): void {
  //  The transport returns what it decoded as `Any`; the cast states what
  //  the decoder was told to build, for a type checker. A string, so it costs
  //  nothing at run time.
  const returns = returnAnnotation(op);
  const call = `${flavour === 'async' ? 'await ' : ''}self._client._request(`;
  w.line(returns === 'None' ? call : `return _cast(${str(returns)}, ${call}`);
  w.indent(() => {
    w.line(`${str(op.httpMethod.toUpperCase())},`);
    w.line(`${pathExpr(op, args)},`);
    emitParamLists(w, op, args);
    const body = args.find((a) => a.role === 'body');
    if (body) {
      const value = bodyExpr(op);
      w.line(body.required ? `body=${value},` : `body=None if body is None else ${value},`);
    }
    if (op.idempotent) w.line('idempotent=True,');
    w.line(`response=${responseExpr(op)},`);
    w.line('request_options=request_options,');
  });
  w.line(returns === 'None' ? ')' : '))');
}

function emitStreamCall(w: Writer, op: Operation, args: Arg[]): void {
  if (op.body) {
    //  A POST answered as an event stream: one attempt, never the GET
    //  stream's reconnect, because a replay would run the work twice.
    if (op.body.encoding !== 'json' || op.httpMethod.toUpperCase() !== 'POST') {
      throw new Error(`${op.id}: an event stream answering a ${op.body.encoding} ${op.httpMethod.toUpperCase()} body is not supported yet.`);
    }
    w.line('return self._client._stream_post(');
    w.indent(() => {
      w.line(`${pathExpr(op, args)},`);
      w.line('body,');
      emitParamLists(w, op, args);
      w.line(`idempotent=${op.idempotent ? 'True' : 'False'},`);
      w.line('request_options=request_options,');
    });
    w.line(')');
    return;
  }
  if (op.httpMethod !== 'get') {
    throw new Error(`${op.id}: an event stream over ${op.httpMethod.toUpperCase()} without a body is not supported yet.`);
  }
  w.line('return self._client._stream(');
  w.indent(() => {
    w.line(`${pathExpr(op, args)},`);
    emitParamLists(w, op, args);
    w.line('request_options=request_options,');
  });
  w.line(')');
}

/** `query=[...]` and `headers=[...]`, in the order the document declares them. */
function emitParamLists(w: Writer, op: Operation, args: Arg[]): void {
  const byLocation = (location: Param['location']) =>
    args.filter((a) => a.role === 'param' && a.param!.location === location);
  const query = byLocation('query');
  const headers = byLocation('header');
  if (query.length > 0) w.line(`query=[${query.map((a) => `(${str(a.param!.wire)}, ${a.name})`).join(', ')}],`);
  if (headers.length > 0) w.line(`headers=[${headers.map((a) => `(${str(a.param!.wire)}, ${a.name})`).join(', ')}],`);
}

function bodyExpr(op: Operation): string {
  const body = op.body!;
  switch (body.encoding) {
    case 'form': {
      //  Schema order, not the caller's: a form body is compared as bytes,
      //  and every SDK sends its fields in the order declared.
      const type = body.type.kind === 'named' ? resolve(body.type.name) : undefined;
      if (type?.kind !== 'object' || type.additional !== null) {
        throw new Error(`${op.id}: a form body must be an object with declared properties only.`);
      }
      return `_Body(body, ${str('form')}, (${type.properties.map((p) => `${str(p.wire)}, `).join('')}))`;
    }
    case 'multipart': {
      const parts = (body.parts ?? []).map((part) => `(${str(part.wire)}, ${part.role === 'file' ? 'True' : 'False'}), `);
      return `_Body(body, ${str('multipart')}, (${parts.join('')}))`;
    }
    case 'binary':
      return body.contentType && body.contentType !== 'application/octet-stream'
        ? `_Body(body, ${str('binary')}, content_type=${str(body.contentType)})`
        : `_Body(body, ${str('binary')})`;
    default:
      //  A text body goes on the wire as a JSON string, as in every other SDK.
      return '_Body(body)';
  }
}

function isBinaryResponse(op: Operation): boolean {
  return op.response.encoding === 'binary' || (op.response.type?.kind === 'prim' && op.response.type.prim === 'binary');
}

function responseExpr(op: Operation): string {
  if (!op.response.type) return '_VOID';
  if (isBinaryResponse(op)) return '_BINARY';
  //  A text media type is not JSON that happens to be a string: parsing a
  //  JSONL export succeeds whenever it holds exactly one line.
  if (op.response.encoding === 'text') return '_TEXT';
  const annotation = pyType(op.response.type, '_m.');
  const type = annotation === 'JsonValue' ? 'None' : annotation;
  return op.response.nullable ? `_Response(type=${type}, nullable=True)` : `_Response(type=${type})`;
}

function returnAnnotation(op: Operation): string {
  if (!op.response.type) return 'None';
  if (isBinaryResponse(op)) return 'bytes';
  if (op.response.encoding === 'text') return 'str';
  const annotation = pyType(op.response.type, '_m.');
  return op.response.nullable ? nullable(annotation) : annotation;
}

function pathExpr(op: Operation, args: Arg[]): string {
  if (op.pathParams.length === 0) return str(op.path);
  let out = '';
  let rest = op.path;
  for (;;) {
    const match = /\{([^}]+)\}/.exec(rest);
    if (!match) {
      out += fstringText(rest);
      break;
    }
    out += fstringText(rest.slice(0, match.index));
    const arg = args.find((a) => a.role === 'path' && a.param!.wire === match[1]);
    if (!arg) throw new Error(`${op.id}: path parameter {${match[1]}} is not declared`);
    out += `{_segment(${arg.name})}`;
    rest = rest.slice(match.index + match[0].length);
  }
  return `f${str(out)}`;
}

function fstringText(text: string): string {
  return text.replace(/\{/g, '{{').replace(/\}/g, '}}');
}

function emitPaginated(w: Writer, op: Operation, group: Group, flavour: 'sync' | 'async'): void {
  const pagination = op.pagination!;
  const args = operationArgs(op);
  const cursor = args.find((a) => a.role === 'param' && a.param!.wire === pagination.cursorParam)!;
  const items = attributeOf(op.response.type, pagination.itemsProp)!;
  const next = attributeOf(op.response.type, pagination.cursorProp)!;
  const hasMore = pagination.hasMoreProp ? attributeOf(op.response.type, pagination.hasMoreProp) : undefined;
  const itemType = pyType(pagination.itemType, '_m.');
  const call = [
    ...args.filter((a) => a.role !== 'param').map((a) => a.name),
    ...args.filter((a) => a.role === 'param').map((a) => `${a.name}=${a.name}`),
    'request_options=request_options',
  ].join(', ');
  const async = flavour === 'async';

  const returns = async ? `AsyncIterator[${itemType}]` : `Iterator[${itemType}]`;
  w.block(`${async ? 'async def' : 'def'} ${paginatedName(op, group)}(${signature(args)}) -> ${returns}:`, () => {
    docstring(
      w,
      `Every item \`${methodName(op)}\` returns, following the \`${pagination.cursorProp}\` cursor until the ` +
        'server reports no further pages. Starts at `' + cursor.name + '` when one is given.',
    );
    w.line('guard = _CursorGuard()');
    w.block('while True:', () => {
      w.line(`page = ${async ? 'await ' : ''}self.${methodName(op)}(${call})`);
      w.line(pagination.itemsOptional ? `items = page.${items} or []` : `items = page.${items}`);
      if (async) {
        w.block('for item in items:', () => {
          w.line('yield item');
        }, '');
      } else {
        w.line('yield from items');
      }
      w.line(`${cursor.name} = guard.advance(page.${next}, ${hasMore ? `page.${hasMore}` : 'None'}, not items)`);
      w.block(`if ${cursor.name} is None:`, () => {
        w.line('return');
      }, '');
    }, '');
  }, '');
}

function paginatedName(op: Operation, group: Group): string {
  const base = `${methodName(op)}_all`;
  return group.operations.some((other) => methodName(other) === base) ? `${methodName(op)}_auto_paging` : base;
}

/**
 * Auto-paging rewrites the cursor, so it needs an optional `cursor` parameter,
 * and it reads the page, so the page has to be a model with those fields.
 */
function canPaginate(op: Operation): boolean {
  const pagination = op.pagination;
  if (!pagination) return false;
  const cursor = op.queryParams.find((p) => p.wire === pagination.cursorParam);
  if (cursor === undefined || cursor.required) return false;
  if (op.response.nullable) return false;
  return (
    attributeOf(op.response.type, pagination.itemsProp) !== undefined &&
    attributeOf(op.response.type, pagination.cursorProp) !== undefined &&
    (pagination.hasMoreProp === undefined || attributeOf(op.response.type, pagination.hasMoreProp) !== undefined)
  );
}

function methodName(op: Operation): string {
  return pythonIdent(snake(op.method));
}

function operationDoc(op: Operation, flavour: 'sync' | 'async'): string {
  const parts: string[] = [];
  if (op.summary) parts.push(op.summary);
  if (op.description && op.description !== op.summary) parts.push(op.description);
  parts.push(`\`${op.httpMethod.toUpperCase()} ${op.path}\``);
  if (op.scopes.length > 0) parts.push(`Required scopes: ${op.scopes.map((s) => `\`${s}\``).join(', ')}.`);
  if (op.sse) {
    parts.push(
      flavour === 'async'
        ? 'Returns a server-sent event stream; iterate it with `async for`.'
        : 'Returns a server-sent event stream; iterate it with `for`.',
    );
  }
  if (op.deprecated) parts.push('Deprecated.');
  return parts.join('\n\n');
}

