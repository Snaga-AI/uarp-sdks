/** A docstring, wrapped, with anything that would end it or escape escaped. */
function docstring(w: Writer, text: string | undefined): void {
  if (!text) return;
  const safe = text.replace(/\\/g, '\\\\').replace(/"""/g, '\\"\\"\\"').replace(/\r/g, '');
  const probe = new Writer(PY_INDENT);
  probe.doc(safe, '');
  const lines = probe.toString().replace(/\n$/, '').split('\n');
  if (lines.length === 1 && !lines[0]!.endsWith('"')) {
    w.line(`"""${lines[0]}"""`);
    return;
  }
  w.line(`"""${lines[0]}`);
  for (const line of lines.slice(1)) w.line(line);
  w.line('"""');
}

function commentLines(text: string): string[] {
  const probe = new Writer(PY_INDENT);
  probe.doc(text.replace(/\r/g, ''), '');
  return probe.toString().replace(/\n$/, '').split('\n');
}

/** A Python string literal. JSON's escapes are all valid Python escapes. */
function str(value: string): string {
  return JSON.stringify(value);
}

