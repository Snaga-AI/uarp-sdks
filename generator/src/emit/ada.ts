/** Ada needs declarations in dependency order; the spec's graph is acyclic. */
function sortByDependency(types: NamedType[]): NamedType[] {
  const byName = new Map(types.map((t) => [t.name, t]));
  const visited = new Set<string>();
  const visiting = new Set<string>();
  const out: NamedType[] = [];

  const dependencies = (type: NamedType): string[] => {
    const names: string[] = [];
    const walk = (ref: TypeRef): void => {
      if (ref.kind === 'named') names.push(ref.name);
      else if (ref.kind === 'array') walk(ref.items);
      else if (ref.kind === 'map') walk(ref.values);
      else if (ref.kind === 'union') ref.variants.forEach(walk);
    };
    if (type.kind === 'object') type.properties.forEach((p) => walk(p.type));
    if (type.kind === 'alias') walk(type.target);
    return names;
  };

  const visit = (name: string): void => {
    if (visited.has(name) || visiting.has(name)) return;
    const type = byName.get(name);
    if (!type) return;
    visiting.add(name);
    for (const dep of dependencies(type)) visit(dep);
    visiting.delete(name);
    visited.add(name);
    out.push(type);
  };

  for (const type of types) visit(type.name);
  return out;
}

/** Named types that appear as array elements need a Vectors instantiation. */
function collectArrayElements(spec: Spec): Set<string> {
  const names = new Set<string>();
  const walk = (ref: TypeRef): void => {
    if (ref.kind === 'array') {
      if (ref.items.kind === 'named') names.add(ref.items.name);
      walk(ref.items);
    } else if (ref.kind === 'map') walk(ref.values);
    else if (ref.kind === 'union') ref.variants.forEach(walk);
  };
  for (const type of spec.types) {
    if (type.kind === 'object') type.properties.forEach((p) => walk(p.type));
    if (type.kind === 'alias') walk(type.target);
  }
  for (const group of spec.groups) {
    for (const op of group.operations) {
      if (op.pagination?.itemType.kind === 'named') names.add(op.pagination.itemType.name);
      //  A top-level array response or body needs its vector instantiation too.
      if (op.response.type) walk(op.response.type);
      if (op.body) walk(op.body.type);
      for (const param of [...op.pathParams, ...op.queryParams, ...op.headerParams]) walk(param.type);
    }
  }
  return names;
}

function comment(w: Writer, text: string | undefined): void {
  if (!text) return;
  w.doc(toAscii(text), '--  ');
}

/** GNAT reads sources as Latin-1 by default, so comments stay ASCII. */
function toAscii(text: string): string {
  return text
    .replace(/[‘’]/g, "'")
    .replace(/[“”]/g, '"')
    .replace(/[–—]/g, '-')
    .replace(/[…]/g, '...')
    .replace(/[^\x20-\x7E\n]/g, '?');
}

function escape(value: string): string {
  return toAscii(value).replace(/"/g, '""').replace(/\n/g, ' ');
}
